/**
 * Fails on Tailwind utilities written in a non-canonical form.
 *
 * This is the diagnostic the Tailwind IntelliSense extension shows in the
 * editor as `tailwindcss(suggestCanonicalClasses)`: `max-w-(--container-site)`
 * when the theme already names it `max-w-site`, `w-[100%]` when `w-full` says
 * the same thing. It has always been editor-only, so nothing stopped a
 * non-canonical class from being committed. This runs the same check headlessly
 * so `pnpm lint` and CI see it too.
 *
 *   pnpm lint:tailwind        report, exit non-zero on findings
 *   pnpm lint:tailwind --fix  rewrite the classes in place
 *
 * Suggestions come from Tailwind's own `canonicalizeCandidates`, so a rewrite
 * always compiles to the same declarations as the class it replaces, and the
 * check follows the theme as tokens are added or renamed.
 *
 * Deliberately a separate process rather than an ESLint rule: the first
 * `canonicalizeCandidates` call builds signature maps for the whole design
 * system and costs a flat ~200MB (steady across thousands of later calls — it
 * is a startup cost, not a leak). Paying that inside ESLint pushed the lint
 * process past what this machine would hand out, and it died with an
 * out-of-memory fault on most runs.
 */
import { __unstable__loadDesignSystem } from 'tailwindcss'
import ts from 'typescript'
import { glob, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import path from 'node:path'

const require = createRequire(import.meta.url)
const ROOT = process.cwd()
const FIX = process.argv.includes('--fix')

/** The stylesheet that imports Tailwind and every `@theme` token. */
const CSS_ENTRY = path.join(ROOT, 'src/app/(frontend)/globals.css')

const SOURCES = 'src/**/*.{ts,tsx}'

/** Generated by Payload — rewriting them is pointless, they come back. */
const IGNORED = new Set(
  ['src/payload-types.ts', 'src/payload-generated-schema.ts'].map((p) => path.join(ROOT, p)),
)

/** JSX attributes whose value is a class list. */
const CLASS_ATTRIBUTES = new Set(['className', 'class'])

/** Helpers whose arguments are class lists. `cn` is `src/utilities/ui.ts`. */
const CLASS_FUNCTIONS = new Set(['cn', 'clsx', 'cva', 'twMerge', 'classNames'])

/**
 * Compiles `globals.css` far enough to answer questions about the theme.
 * `__unstable__loadDesignSystem` is Tailwind's own entry point for tooling and
 * is what IntelliSense uses; the name is unstable, so `tailwindcss` is pinned in
 * package.json and this is the only place it is called.
 */
async function loadDesignSystem() {
  const resolve = (id, base) =>
    id.startsWith('.') ? path.resolve(base, id) : require.resolve(id, { paths: [base, ROOT] })

  return __unstable__loadDesignSystem(await readFile(CSS_ENTRY, 'utf8'), {
    base: path.dirname(CSS_ENTRY),
    async loadStylesheet(id, base) {
      // `@import 'tailwindcss'` has to land on the package's CSS, not its JS entry.
      const file =
        id === 'tailwindcss' ? require.resolve('tailwindcss/index.css') : resolve(id, base)
      return { base: path.dirname(file), content: await readFile(file, 'utf8') }
    },
    async loadModule(id, base) {
      const file = resolve(id, base)
      const mod = await import(pathToFileURL(file).href)
      return { base: path.dirname(file), module: mod.default ?? mod, path: file }
    },
    async loadPlugin(id, base) {
      const mod = await import(pathToFileURL(resolve(id, base)).href)
      return mod.default ?? mod
    },
  })
}

/**
 * Candidates are canonicalised one at a time on purpose. Given a whole class
 * list, `canonicalizeCandidates` also merges and de-duplicates it — `mx-2 my-2`
 * collapses to `m-2` — which is a broader edit than the editor suggests and
 * would reshuffle class lists on every fix.
 */
function canonicaliser(designSystem) {
  const cache = new Map()

  return (candidate) => {
    if (!cache.has(candidate)) {
      const [canonical, ...rest] = designSystem.canonicalizeCandidates([candidate])
      // Anything Tailwind cannot parse comes back untouched. A result that is
      // not one-to-one is not a rename that can be applied in place.
      cache.set(candidate, rest.length === 0 && canonical ? canonical : candidate)
    }
    return cache.get(candidate)
  }
}

/**
 * Every class-list string in a file, as offsets into the raw source. Template
 * literals are visited chunk by chunk so the `${...}` holes between them are
 * left alone.
 */
function collectClassLiterals(source) {
  // Keyed by offset: a `className={cn(...)}` is both a class attribute and a
  // class function, so the same literal is reached twice.
  const found = new Map()

  const addLiteral = (node) => {
    const raw = source.text.slice(node.getStart(source), node.getEnd())
    // Trim the delimiters: a quote or backtick, plus the interpolation braces
    // that bracket the interior chunks of a template literal.
    const tail = raw.endsWith('${') ? 2 : 1
    const start = node.getStart(source) + 1
    found.set(start, { start, text: raw.slice(1, raw.length - tail) })
  }

  // Anything string-shaped under a class context is a class list: bare strings,
  // both arms of a ternary, `clsx` object keys, template chunks.
  const collectFrom = (node) => {
    if (
      ts.isStringLiteral(node) ||
      ts.isNoSubstitutionTemplateLiteral(node) ||
      ts.isTemplateHead(node) ||
      ts.isTemplateMiddle(node) ||
      ts.isTemplateTail(node)
    ) {
      addLiteral(node)
    }
    node.forEachChild(collectFrom)
  }

  const visit = (node) => {
    if (ts.isJsxAttribute(node) && CLASS_ATTRIBUTES.has(node.name.getText(source))) {
      if (node.initializer) collectFrom(node.initializer)
    } else if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      CLASS_FUNCTIONS.has(node.expression.text)
    ) {
      for (const arg of node.arguments) collectFrom(arg)
    }
    node.forEachChild(visit)
  }

  visit(source)
  return [...found.values()].sort((a, b) => a.start - b.start)
}

const canonicalise = canonicaliser(await loadDesignSystem())

const files = []
for await (const entry of glob(SOURCES, { cwd: ROOT })) {
  const absolute = path.join(ROOT, entry)
  if (!IGNORED.has(absolute)) files.push(absolute)
}
files.sort()

const findings = []

for (const file of files) {
  const text = await readFile(file, 'utf8')
  if (!text.includes('className') && !text.includes('cn(')) continue

  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const edits = []

  for (const literal of collectClassLiterals(source)) {
    for (const match of literal.text.matchAll(/\S+/g)) {
      const written = match[0]
      const suggestion = canonicalise(written)
      if (suggestion === written) continue

      const start = literal.start + match.index
      const { line, character } = source.getLineAndCharacterOfPosition(start)
      findings.push({
        file: path.relative(ROOT, file).replaceAll(path.sep, '/'),
        line: line + 1,
        column: character + 1,
        written,
        suggestion,
      })
      edits.push({ start, end: start + written.length, suggestion })
    }
  }

  if (FIX && edits.length > 0) {
    // Back to front, so the earlier offsets stay valid.
    let patched = text
    for (const edit of edits.reverse()) {
      patched = patched.slice(0, edit.start) + edit.suggestion + patched.slice(edit.end)
    }
    await writeFile(file, patched)
  }
}

if (findings.length === 0) {
  console.log(`No non-canonical Tailwind classes in ${files.length} files.`)
  process.exit(0)
}

for (const finding of findings) {
  const { file, line, column, written, suggestion } = finding
  console.log(`${file}:${line}:${column}  ${written}  ->  ${suggestion}`)
}

const count = `${findings.length} non-canonical Tailwind class(es)`
console.log(
  FIX ? `\nRewrote ${count}.` : `\nFound ${count}. Fix them with: pnpm lint:tailwind --fix`,
)
process.exit(FIX ? 0 : 1)
